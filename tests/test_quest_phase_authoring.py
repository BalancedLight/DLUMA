@pytest.mark.skipif(os.name != "nt", reason="Windows file sharing contract")
def test_lowered_source_allows_compiler_reads_and_denies_mutation(tmp_path: Path) -> None:
    import ctypes
    from ctypes import wintypes
    import subprocess

    source = (ROOT / "src/dlw_quest_authoring.c").read_text(encoding="utf-8")
    start = source.index("static int dluma_quest_authoring_lock_compiler_source(")
    end = source.index("\nstatic int dluma_quest_authoring_create_lowered_source(", start)
    helper = source[start:end].replace("static int", "__declspec(dllexport) int", 1)
    harness = tmp_path / "source_lock.c"
    harness.write_text('#include "dlw_win32.h"\n' + helper, encoding="utf-8")
    build = tmp_path / "build.bat"
    build.write_text(
        '@echo off\n'
        f'call "{ROOT / "tools/setup_msvc.bat"}" || exit /b 1\n'
        f'cd /d "{tmp_path}"\n'
        f'cl /nologo /LD /W4 /WX /I"{ROOT / "src"}" source_lock.c '
        '/link kernel32.lib /out:source_lock.dll\n',
        encoding="utf-8",
    )
    subprocess.run(["cmd.exe", "/d", "/c", str(build)], check=True,
                   capture_output=True, text=True, timeout=90)
    library = ctypes.CDLL(str(tmp_path / "source_lock.dll"))
    transfer = library.dluma_quest_authoring_lock_compiler_source
    transfer.argtypes = [ctypes.POINTER(wintypes.HANDLE)]
    transfer.restype = wintypes.BOOL
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                                  ctypes.c_void_p, wintypes.DWORD, wintypes.DWORD,
                                  wintypes.HANDLE]
    kernel.CreateFileW.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel.CloseHandle.restype = wintypes.BOOL
    invalid = wintypes.HANDLE(-1).value
    path = tmp_path / "lowered.pxsl"
    path.write_bytes(b"Quest -name=<<Fixture>>\n")
    read, write, delete, share_read = 0x80000000, 0x40000000, 0x10000, 1

    def open_file(access: int, sharing: int = share_read):
        return kernel.CreateFileW(str(path), access, sharing, None, 3, 0x80, None)

    handle = wintypes.HANDLE(open_file(read | write))
    assert handle.value != invalid
    try:
        # Reproduce the bug before transferring the production handle.
        assert open_file(read) == invalid
        assert ctypes.get_last_error() == 32
        assert transfer(ctypes.byref(handle))
        reader = open_file(read)
        assert reader != invalid
        kernel.CloseHandle(reader)
        # Even a caller willing to share everything cannot mutate this source.
        for access in (write, delete):
            assert open_file(access, 7) == invalid
            assert ctypes.get_last_error() == 32
        assert path.read_bytes() == b"Quest -name=<<Fixture>>\n"
    finally:
        kernel.CloseHandle(handle)
