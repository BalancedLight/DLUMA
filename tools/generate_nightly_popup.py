"""Generate the custom-menu nightly popup from the bundled main menu."""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'PakAssets/XUI/DLUMA_Main_PC_workshop.xui'
OUTPUT = ROOT / 'src/dlw_nightly_popup_template.h'


def generated_header() -> str:
    root = ET.fromstring(SOURCE.read_bytes())
    matches = [group for scene in root.findall('XuiScene')
               for group in scene.findall('AdvGroup')
               if group.findtext('Properties/Id') == 'G_DLUMANightlyPopup']
    if len(matches) != 1:
        raise ValueError('Expected exactly one nightly popup in the bundled main menu')
    popup = matches[0]
    ids = {item.text for item in popup.iter('Id')}
    required = {'G_DLUMANightlyPopup', 'T_DLUMANightlyText',
                'B_DLUMANightlyYes', 'B_DLUMANightlyNo', 'B_DLUMANightlyOk'}
    if not required.issubset(ids):
        raise ValueError('Bundled nightly popup is missing required controls')
    data = ET.tostring(popup, encoding='utf-8', short_empty_elements=True)
    rows = ['    ' + ', '.join('0x%02x' % value for value in data[i:i + 16]) + ','
            for i in range(0, len(data), 16)]
    return ('/* Generated by python tools/generate_nightly_popup.py. */\n'
            '#ifndef DLUMA_NIGHTLY_POPUP_TEMPLATE_H\n#define DLUMA_NIGHTLY_POPUP_TEMPLATE_H\n'
            'static const unsigned char dluma_nightly_popup_template[] = {\n'
            + '\n'.join(rows) + '\n};\n#endif\n')


def validate() -> None:
    if not OUTPUT.exists() or OUTPUT.read_text(encoding='ascii') != generated_header():
        raise ValueError('Nightly popup template is stale; run python tools/generate_nightly_popup.py')


if __name__ == '__main__':
    OUTPUT.write_text(generated_header(), encoding='ascii', newline='\n')
