#!/usr/bin/env python3
"""Generate every public DLUMA API 1.0 contract from the canonical catalog.

The catalog is intentionally plain JSON so the no-CRT native loader, managed
host, Lua helper, editor tooling, documentation, and package verifier can all
consume checked artifacts without importing this generator at runtime.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Iterable


ROOT = Path(__file__).resolve().parents[1]
CATALOG_DIR = ROOT / "api" / "catalog"

GENERATED_NOTICE = "Generated by tools/generate_api.py. Do not edit by hand."

C_TYPE_MAP = {
    "u32": "uint32_t",
    "u64": "uint64_t",
    "i32": "int32_t",
    "f32": "float",
    "f64": "double",
    "bool": "uint32_t",
    "string_view": "DlumaStringView",
    "string_buffer": "DlumaStringBuffer",
    "byte_buffer": "DlumaByteBuffer",
    "object_handle": "DlumaObjectHandle",
    "vec3": "DlumaVec3",
    "scalar": "DlumaScalar",
}

CS_TYPE_MAP = {
    "u32": "uint",
    "u64": "ulong",
    "i32": "int",
    "f32": "float",
    "f64": "double",
    "bool": "bool",
    "string_view": "string",
    "string_buffer": "string",
    "byte_buffer": "byte[]",
    "object_handle": "DlumaObjectHandle",
    "vec3": "DlumaVec3",
    "scalar": "DlumaValue",
}


class CatalogError(ValueError):
    pass


def read_json(path: Path) -> dict[str, Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise CatalogError(f"{path.relative_to(ROOT)}: {exc}") from exc


def canonical_json(value: Any) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        .encode("utf-8")
    )


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in value.split("_"))


def macro(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", value).upper()


def service_type(domain: str) -> str:
    return f"Dluma{pascal(domain)}V1"


def operation_member(operation_id: str, domain: str) -> str:
    prefix = f"{domain}."
    tail = operation_id[len(prefix) :] if operation_id.startswith(prefix) else operation_id
    return tail.replace(".", "_")


def c_operation_member(operation: dict[str, Any], domain: str) -> str:
    adapter = operation.get("adapters", {}).get("c", "")
    if adapter:
        return adapter.rsplit(".", 1)[-1]
    return operation_member(operation["id"], domain)


def cpp_operation_member(operation: dict[str, Any], domain: str) -> str:
    adapter = operation.get("adapters", {}).get("cpp", "")
    if adapter:
        match = re.search(r"\.([A-Za-z_][A-Za-z0-9_]*)$", adapter)
        if match:
            return match.group(1)
    return operation_member(operation["id"], domain)


def method_name(operation_id: str, domain: str) -> str:
    return pascal(operation_member(operation_id, domain))


def load_catalog() -> dict[str, Any]:
    index = read_json(CATALOG_DIR / "catalog.json")
    capabilities_doc = read_json(CATALOG_DIR / "capabilities.json")
    access_doc = read_json(CATALOG_DIR / "access.json")
    types_doc = read_json(CATALOG_DIR / "types.json")
    abi_baseline = read_json(CATALOG_DIR / "abi-baseline.json")

    required_index = {
        "api",
        "domains",
        "status_values",
        "thread_affinities",
        "scopes",
        "languages",
    }
    missing = required_index - index.keys()
    if missing:
        raise CatalogError(f"catalog.json: missing {sorted(missing)}")
    if index["api"]["name"] != "DLUMA API":
        raise CatalogError("catalog.json: unexpected API name")
    if index["api"]["version"] != "1.0":
        raise CatalogError("catalog.json: generator only accepts DLUMA API 1.0")

    capabilities = capabilities_doc.get("capabilities")
    access = access_doc.get("access")
    types = types_doc.get("types")
    if not isinstance(capabilities, list) or not capabilities:
        raise CatalogError("capabilities.json: capabilities must be a non-empty array")
    if not isinstance(access, list) or not access:
        raise CatalogError("access.json: access must be a non-empty array")
    if not isinstance(types, list) or not types:
        raise CatalogError("types.json: types must be a non-empty array")

    capability_names: set[str] = set()
    capability_ids: set[int] = set()
    for item in capabilities:
        if item["name"] in capability_names:
            raise CatalogError(f"duplicate capability name: {item['name']}")
        if item["id"] in capability_ids:
            raise CatalogError(f"duplicate capability ID: {item['id']}")
        capability_names.add(item["name"])
        capability_ids.add(item["id"])
    if capability_ids != set(sorted(capability_ids)):
        raise CatalogError("capability IDs are not stable integers")

    access_names: set[str] = set()
    access_ids: set[int] = set()
    for item in access:
        if item["name"] in access_names:
            raise CatalogError(f"duplicate access name: {item['name']}")
        if item["id"] in access_ids:
            raise CatalogError(f"duplicate access ID: {item['id']}")
        access_names.add(item["name"])
        access_ids.add(item["id"])

    type_names: set[str] = set()
    for record in types:
        name = record.get("name")
        if not isinstance(name, str) or not re.fullmatch(r"Dluma[A-Za-z0-9]+", name):
            raise CatalogError(f"invalid record name: {name!r}")
        if name in type_names:
            raise CatalogError(f"duplicate record type: {name}")
        type_names.add(name)
        field_names: set[str] = set()
        for field in record.get("fields", []):
            field_name = field.get("name")
            field_type = field.get("type")
            if field_name in field_names:
                raise CatalogError(f"{name}: duplicate field {field_name}")
            field_names.add(field_name)
            if field_type not in C_TYPE_MAP and field_type not in type_names:
                # Forward Dluma references are allowed and checked after all types load.
                if not isinstance(field_type, str) or not field_type.startswith("Dluma"):
                    raise CatalogError(f"{name}.{field_name}: unknown type {field_type!r}")
            if field.get("pointer") and not field.get("count_field"):
                raise CatalogError(f"{name}.{field_name}: pointer fields need count_field")
        for field in record.get("fields", []):
            count_field = field.get("count_field")
            if count_field and count_field not in field_names:
                raise CatalogError(
                    f"{name}.{field['name']}: unknown count field {count_field}"
                )
    for record in types:
        for field in record.get("fields", []):
            field_type = field["type"]
            if field_type.startswith("Dluma") and field_type not in type_names:
                raise CatalogError(
                    f"{record['name']}.{field['name']}: unknown record {field_type}"
                )

    domains: list[dict[str, Any]] = []
    operation_ids: set[str] = set()
    service_ids: set[str] = set()
    for domain_index, domain_name in enumerate(index["domains"], start=1):
        path = CATALOG_DIR / f"{domain_name}.json"
        domain = read_json(path)
        if domain.get("domain") != domain_name:
            raise CatalogError(f"{path.name}: domain does not match catalog index")
        service = domain.get("service", {})
        expected_service = f"dluma.{domain_name}.v1"
        if service.get("id") != expected_service:
            raise CatalogError(
                f"{path.name}: service must be {expected_service}, got {service.get('id')}"
            )
        if service["id"] in service_ids:
            raise CatalogError(f"duplicate service ID: {service['id']}")
        service_ids.add(service["id"])
        ordinal_ids: set[int] = set()
        operations = domain.get("operations")
        if not isinstance(operations, list) or not operations:
            raise CatalogError(f"{path.name}: operations must be a non-empty array")
        for operation in operations:
            operation_id = operation.get("id")
            ordinal = operation.get("ordinal")
            if not isinstance(operation_id, str) or not operation_id.startswith(
                f"{domain_name}."
            ):
                raise CatalogError(
                    f"{path.name}: operation {operation_id!r} must use {domain_name}. prefix"
                )
            if operation_id in operation_ids:
                raise CatalogError(f"duplicate operation ID: {operation_id}")
            operation_ids.add(operation_id)
            if not isinstance(ordinal, int) or ordinal < 1 or ordinal in ordinal_ids:
                raise CatalogError(f"{operation_id}: invalid or duplicate ordinal")
            ordinal_ids.add(ordinal)
            operation["numeric_id"] = domain_index * 1000 + ordinal
            if operation.get("status") not in index["status_values"]:
                raise CatalogError(f"{operation_id}: invalid status")
            if operation.get("capability") not in capability_names:
                raise CatalogError(
                    f"{operation_id}: unknown capability {operation.get('capability')}"
                )
            unknown_access = set(operation.get("access", [])) - access_names
            if unknown_access:
                raise CatalogError(
                    f"{operation_id}: unknown access {sorted(unknown_access)}"
                )
            unknown_scopes = set(operation.get("scopes", [])) - set(index["scopes"])
            if unknown_scopes or not operation.get("scopes"):
                raise CatalogError(f"{operation_id}: invalid scopes")
            if operation.get("thread") not in index["thread_affinities"]:
                raise CatalogError(f"{operation_id}: invalid thread affinity")
            if operation.get("request") not in type_names:
                raise CatalogError(f"{operation_id}: unknown request record")
            if operation.get("result") not in type_names:
                raise CatalogError(f"{operation_id}: unknown result record")
            adapters = operation.get("adapters", {})
            expected_adapters = {"core", "lua", "csharp", "c", "cpp"}
            if set(adapters) != expected_adapters:
                raise CatalogError(
                    f"{operation_id}: adapters must be {sorted(expected_adapters)}"
                )
            if operation["status"] in {"implemented", "gated"} and not adapters["core"]:
                raise CatalogError(
                    f"{operation_id}: implemented/gated operation needs a core adapter"
                )
            if operation["status"] in {"planned", "removed"} and adapters["core"]:
                raise CatalogError(
                    f"{operation_id}: planned/removed operation must not claim an adapter"
                )
            if not operation.get("tests"):
                raise CatalogError(f"{operation_id}: missing test requirements")
        if sorted(ordinal_ids) != list(range(1, len(ordinal_ids) + 1)):
            raise CatalogError(f"{path.name}: operation ordinals must be contiguous")
        domain["operations"] = sorted(operations, key=lambda item: item["ordinal"])
        baseline_operations = abi_baseline.get("services", {}).get(service["id"])
        if not isinstance(baseline_operations, list):
            raise CatalogError(
                f"abi-baseline.json: missing service {service['id']}"
            )
        current_operations = [item["id"] for item in domain["operations"]]
        if current_operations[: len(baseline_operations)] != baseline_operations:
            raise CatalogError(
                f"{service['id']}: incompatible table change; existing operations "
                "must retain their order and new operations must append"
            )
        domains.append(domain)

    expected_services = {domain["service"]["id"] for domain in domains}
    baseline_services = set(abi_baseline.get("services", {}))
    if baseline_services != expected_services:
        raise CatalogError(
            "abi-baseline.json: service set differs from the catalog index"
        )

    merged: dict[str, Any] = {
        "api": index["api"],
        "status_values": index["status_values"],
        "thread_affinities": index["thread_affinities"],
        "scopes": index["scopes"],
        "languages": index["languages"],
        "capabilities": sorted(capabilities, key=lambda item: item["id"]),
        "access": sorted(access, key=lambda item: item["id"]),
        "types": types,
        "domains": domains,
    }
    digest = hashlib.sha256(canonical_json(merged)).hexdigest().upper()
    merged["catalog_sha256"] = digest
    return merged


def generated_json(catalog: dict[str, Any]) -> str:
    return json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"


def c_field_type(field: dict[str, Any], is_result: bool) -> str:
    field_type = C_TYPE_MAP.get(field["type"], field["type"])
    if field.get("pointer"):
        prefix = "" if is_result else "const "
        return f"{prefix}{field_type}*"
    return field_type


