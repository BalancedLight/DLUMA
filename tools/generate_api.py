def check_outputs(outputs: dict[Path, str]) -> list[str]:
    stale: list[str] = []
    for path, expected in outputs.items():
        try:
            actual = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            stale.append(f"missing: {path.relative_to(ROOT)}")
            continue
        if actual != expected:
            stale.append(f"stale: {path.relative_to(ROOT)}")
    return stale


def write_outputs(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.generate-{os.getpid()}.tmp")
        try:
            temporary.write_text(content, encoding="utf-8", newline="\n")
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def parse_args(argv: Iterable[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail if generated files drift")
    mode.add_argument("--write", action="store_true", help="regenerate checked artifacts")
    return parser.parse_args(list(argv))


def main(argv: Iterable[str] = ()) -> int:
    args = parse_args(argv)
    try:
        catalog = load_catalog()
        outputs = render_outputs(catalog)
        if args.write:
            write_outputs(outputs)
            print(
                f"generated {len(outputs)} DLUMA API artifacts "
                f"({catalog['catalog_sha256']})"
            )
            return 0
        stale = check_outputs(outputs)
        if stale:
            print("\n".join(stale), file=sys.stderr)
            print("run: python tools/generate_api.py --write", file=sys.stderr)
            return 1
        print(
            f"DLUMA API artifacts are current ({catalog['catalog_sha256']})"
        )
        return 0
    except CatalogError as exc:
        print(f"catalog error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
