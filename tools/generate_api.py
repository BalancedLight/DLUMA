def render_matrix(catalog: dict[str, Any]) -> str:
    lines = [
        f"<!-- {GENERATED_NOTICE} -->",
        "# DLUMA API 1.0 capability matrix",
        "",
        "| ID | Capability | Operations | Statuses |",
        "|---:|---|---:|---|",
    ]
    operations = [
        operation
        for domain in catalog["domains"]
        for operation in domain["operations"]
    ]
    for capability in catalog["capabilities"]:
        relevant = [
            operation
            for operation in operations
            if operation["capability"] == capability["name"]
        ]
        statuses = sorted({operation["status"] for operation in relevant})
        lines.append(
            f"| {capability['id']} | `{capability['name']}` | {len(relevant)} | "
            f"{', '.join(statuses) if statuses else 'reserved'} |"
        )
    lines.append("")
    return "\n".join(lines)


