def render_operation_policy_header(catalog: dict[str, Any]) -> str:
    capability_ids = {
        item["name"]: item["id"] for item in catalog["capabilities"]
    }
    access_ids = {item["name"]: item["id"] for item in catalog["access"]}
    status_ids = {
        "implemented": 1,
        "gated": 2,
        "planned": 3,
        "removed": 4,
    }
    scope_bits = {"global": 1, "project": 2, "map": 4}
    lines = [
        f"/* {GENERATED_NOTICE} */",
        "#ifndef DLUMA_API_OPERATIONS_GENERATED_H",
        "#define DLUMA_API_OPERATIONS_GENERATED_H",
        "",
        "#define DLUMA_OPERATION_IMPLEMENTED 1U",
        "#define DLUMA_OPERATION_GATED 2U",
        "#define DLUMA_OPERATION_PLANNED 3U",
        "#define DLUMA_OPERATION_REMOVED 4U",
        "#define DLUMA_OPERATION_THREAD_ANY 0U",
        "#define DLUMA_OPERATION_THREAD_GAME 1U",
        "#define DLUMA_OPERATION_SCOPE_GLOBAL 1U",
        "#define DLUMA_OPERATION_SCOPE_PROJECT 2U",
        "#define DLUMA_OPERATION_SCOPE_MAP 4U",
        "",
        "typedef struct DlumaOperationPolicy {",
        "    uint32_t operation_id;",
        "    uint32_t capability_id;",
        "    uint32_t access_id;",
        "    uint32_t scope_mask;",
        "    uint32_t thread_affinity;",
        "    uint32_t catalog_status;",
        "    const char* capability_name;",
        "    const char* access_name;",
        "} DlumaOperationPolicy;",
        "",
        "static const DlumaOperationPolicy g_dluma_generated_operation_policies[] = {",
    ]
    for domain in catalog["domains"]:
        for operation in domain["operations"]:
            mask = sum(scope_bits[item] for item in operation["scopes"])
            access_id = (
                access_ids[operation["access"][0]] if operation["access"] else 0
            )
            thread = 1 if operation["thread"] == "game" else 0
            lines.append(
                "    {{{numeric}U, {capability}U, {access}U, {scope}U, "
                "{thread}U, {status}U, \"{capability_name}\", "
                "\"{access_name}\"}},".format(
                    numeric=operation["numeric_id"],
                    capability=capability_ids[operation["capability"]],
                    access=access_id,
                    scope=mask,
                    thread=thread,
                    status=status_ids[operation["status"]],
                    capability_name=operation["capability"],
                    access_name=(operation["access"][0]
                                 if operation["access"] else ""),
                )
            )
    lines.extend(
        [
            "};",
            "",
            "#define DLUMA_GENERATED_OPERATION_POLICY_COUNT \\",
            "    ((uint32_t)(sizeof(g_dluma_generated_operation_policies) / \\",
            "                sizeof(g_dluma_generated_operation_policies[0])))",
            "",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines)


