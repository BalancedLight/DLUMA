def render_cpp_header(catalog: dict[str, Any]) -> str:
    lines = [
        f"// {GENERATED_NOTICE}",
        "#ifndef DLUMA_HPP",
        "#define DLUMA_HPP",
        "",
        '#include "../c/dluma_api.h"',
        "#include <cstdint>",
        "#include <cstring>",
        "#include <string_view>",
        "",
        "namespace dluma {",
        "",
        "inline DlumaStringView string_view(std::string_view value) noexcept {",
        "    return {value.data(), static_cast<std::uint64_t>(value.size())};",
        "}",
        "",
        "template <typename Table>",
        "class service_ref {",
        "public:",
        "    constexpr service_ref() noexcept = default;",
        "    explicit constexpr service_ref(const Table* table) noexcept : table_(table) {}",
        "    explicit constexpr operator bool() const noexcept { return table_ != nullptr; }",
        "protected:",
        "    const Table* table_ = nullptr;",
        "};",
        "",
    ]
    for domain in catalog["domains"]:
        domain_name = domain["domain"]
        class_name = f"{domain_name}_service"
        type_name = service_type(domain_name)
        lines.extend(
            [
                f"class {class_name} final : public service_ref<{type_name}> {{",
                "public:",
                f"    using service_ref<{type_name}>::service_ref;",
            ]
        )
        for operation in domain["operations"]:
            member = c_operation_member(operation, domain_name)
            wrapper = cpp_operation_member(operation, domain_name)
            lines.extend(
                [
                    f"    DlumaStatus {wrapper}(const {operation['request']}& request,",
                    f"                     {operation['result']}& result) const noexcept {{",
                    f"        if (!table_ || !table_->{member}) return DLUMA_STATUS_UNAVAILABLE;",
                    f"        return table_->{member}(table_->context, &request, &result);",
                    "    }",
                ]
            )
        lines.extend(["};", ""])

    lines.extend(
        [
            "class context final {",
            "public:",
            "    explicit constexpr context(const DlumaApiV1* api) noexcept : api_(api) {}",
            "    explicit constexpr operator bool() const noexcept {",
            "        return api_ && api_->abi_version == DLUMA_API_ABI_VERSION && api_->get_service;",
            "    }",
            "",
        ]
    )
    for domain in catalog["domains"]:
        domain_name = domain["domain"]
        type_name = service_type(domain_name)
        lines.extend(
            [
                f"    {domain_name}_service {domain_name}() const noexcept {{",
                f"        {type_name} table{{}};",
                "        table.struct_size = sizeof(table);",
                f"        if (!load(DLUMA_SERVICE_{macro(domain_name)}_V1, table)) return {{}};",
                f"        storage_{domain_name}_ = table;",
                f"        return {domain_name}_service(&storage_{domain_name}_);",
                "    }",
                "",
            ]
        )
    lines.extend(
        [
            "private:",
            "    template <typename Table>",
            "    bool load(const char* id, Table& table) const noexcept {",
            "        if (!static_cast<bool>(*this)) return false;",
            "        const DlumaStringView view{id, static_cast<std::uint64_t>(std::strlen(id))};",
            "        return api_->get_service(api_->context, view, 1, &table, sizeof(table))",
            "            == DLUMA_STATUS_OK;",
            "    }",
            "    const DlumaApiV1* api_ = nullptr;",
        ]
    )
    for domain in catalog["domains"]:
        domain_name = domain["domain"]
        lines.append(f"    mutable {service_type(domain_name)} storage_{domain_name}_{{}};")
    lines.extend(["};", "", "} // namespace dluma", "", "#endif", ""])
    return "\n".join(lines)


def cs_type(field: dict[str, Any]) -> str:
    value = CS_TYPE_MAP.get(field["type"], field["type"])
    if field.get("pointer"):
        return f"IReadOnlyList<{value}>"
    return value


